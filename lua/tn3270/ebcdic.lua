    [0xF5] = '5', [0xF6] = '6', [0xF7] = '7', [0xF8] = '8', [0xF9] = '9',
}

M.to_ebcdic = {}
for k, v in pairs(M.to_ascii) do
    M.to_ebcdic[v] = k
end

function M.decode(byte)
    return M.to_ascii[byte] or '.'
end

function M.encode(char)
    return M.to_ebcdic[char] or 0x40
end

return M
