    [0x40] = ' ',
    [0x4B] = '.', [0x4C] = '<', [0x4D] = '(', [0x4E] = '+', [0x4F] = '|',
    [0x50] = '&',
    [0x5A] = '!', [0x5B] = '$', [0x5C] = '*', [0x5D] = ')', [0x5E] = ';',
    [0x60] = '-', [0x61] = '/',
    [0x6B] = ',', [0x6C] = '%', [0x6D] = '_', [0x6E] = '>', [0x6F] = '?',
    [0x7A] = ':', [0x7B] = '#', [0x7C] = '@', [0x7D] = "'", [0x7E] = '=',
    [0x7F] = '"',

    [0x81] = 'a', [0x82] = 'b', [0x83] = 'c', [0x84] = 'd',
    [0x85] = 'e', [0x86] = 'f', [0x87] = 'g', [0x88] = 'h', [0x89] = 'i',
    [0x91] = 'j', [0x92] = 'k', [0x93] = 'l', [0x94] = 'm',
    [0x95] = 'n', [0x96] = 'o', [0x97] = 'p', [0x98] = 'q', [0x99] = 'r',
    [0xA2] = 's', [0xA3] = 't', [0xA4] = 'u', [0xA5] = 'v',
    [0xA6] = 'w', [0xA7] = 'x', [0xA8] = 'y', [0xA9] = 'z',

    [0xC1] = 'A', [0xC2] = 'B', [0xC3] = 'C', [0xC4] = 'D',
    [0xC5] = 'E', [0xC6] = 'F', [0xC7] = 'G', [0xC8] = 'H', [0xC9] = 'I',
